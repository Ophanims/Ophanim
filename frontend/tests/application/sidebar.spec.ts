import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import template from "../../src/features/simulation/contracts/default_project.json";
import { route_path } from "../../src/features/simulation/communication/config";
import type { Project } from "../../src/features/simulation/contracts/generated";

test("four sidebar panels provide persistent ground station CRUD", async ({ page, request }) => {
  const project = structuredClone(template);
  project.project_id = `sidebar_${randomUUID().replaceAll("-", "")}`;
  project.title = "Sidebar verification";
  project.seed = 37;
  const created = await request.post(route_path("save_project"), { data: project });
  expect(created.ok(), await created.text()).toBeTruthy();
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const stored_project = async () => (await (await request.get(route_path("get_project", { project_id: project.project_id }))).json()).data as Project;
  try {
    await page.goto(`/workspace/${project.project_id}`);
    await expect(page.getByRole("heading", { name: project.title, exact: true })).toBeVisible({ timeout: 30_000 });
    const rail = page.getByRole("tablist", { name: "Workspace panels" });
    await expect(rail.getByRole("tab")).toHaveCount(4);
    for (const label of ["Satellites", "Ground Stations", "Network", "Tasks"]) await expect(rail.getByRole("tab", { name: label, exact: true })).toBeVisible();
    await expect(rail.getByRole("tab", { name: "Satellites", exact: true })).toHaveAttribute("aria-selected", "true");
    await rail.getByRole("tab", { name: "Ground Stations", exact: true }).click();
    const panel = page.getByRole("tabpanel", { name: "Ground Stations", exact: true });
    await panel.getByRole("button", { name: "Add", exact: true }).click();
    const editor = page.getByRole("dialog", { name: "Add ground station", exact: true });
    const coordinates = await Promise.all(["Latitude (deg)", "Longitude (deg)", "Altitude (m)"].map((name) =>
      editor.getByRole("spinbutton", { name, exact: true }).boundingBox()));
    expect(Math.max(...coordinates.map((box) => box!.y)) - Math.min(...coordinates.map((box) => box!.y))).toBeLessThan(2);
    await editor.getByRole("button", { name: "Pick location", exact: true }).click();
    const picker = page.getByRole("dialog", { name: "Select location", exact: true });
    await picker.locator(".leaflet-container").click({ position: { x: 300, y: 180 } });
    await expect(picker.locator(".leaflet-marker-icon")).toBeVisible();
    await picker.getByRole("button", { name: "Confirm", exact: true }).click();
    await expect(editor.getByRole("img", { name: "Ground station map preview", exact: true })).toBeVisible();
    await expect(editor.locator(".leaflet-marker-icon")).toBeVisible();
    await editor.getByRole("textbox", { name: "Name", exact: true }).fill("Test station");
    await editor.getByRole("spinbutton", { name: "Latitude (deg)", exact: true }).fill("12.5");
    await editor.getByRole("spinbutton", { name: "Longitude (deg)", exact: true }).fill("75.2");
    await editor.getByRole("spinbutton", { name: "Altitude (m)", exact: true }).fill("20");
    await page.screenshot({ path: "test-results/ground-station-location-preview.png" });
    await editor.getByRole("button", { name: "Save station", exact: true }).click();
    await expect(editor).not.toBeVisible();
    await expect(panel.getByText("Test station", { exact: true })).toBeVisible();
    const first = await stored_project();
    expect(first.seed).toBe(37);
    expect(first.ground_stations).toHaveLength(1);
    expect(first.ground_stations[0].location).toEqual({ lat: 12.5, lon: 75.2 });
    const station_id = first.ground_stations[0].id;
    await page.reload();
    await rail.getByRole("tab", { name: "Ground Stations", exact: true }).click();
    await panel.getByRole("button", { name: "Edit Test station", exact: true }).click();
    const edit = page.getByRole("dialog", { name: "Edit ground station", exact: true });
    await expect(edit.getByRole("spinbutton", { name: "Altitude (m)", exact: true })).toHaveValue("20");
    await expect(edit.getByRole("img", { name: "Ground station map preview", exact: true })).toBeVisible();
    await edit.getByRole("textbox", { name: "Name", exact: true }).fill("Updated station");
    await edit.getByRole("spinbutton", { name: "Altitude (m)", exact: true }).fill("100");
    await edit.getByRole("button", { name: "Save station", exact: true }).click();
    await expect(edit).not.toBeVisible();
    const updated = await stored_project();
    expect(updated.ground_stations[0].id).toBe(station_id);
    expect(updated.ground_stations[0].name).toBe("Updated station");
    expect(updated.ground_stations[0].altitude_m).toBe(100);
    await panel.getByRole("textbox", { name: "Search Ground Stations", exact: true }).fill("not found");
    await expect(panel.getByText("No matching stations.", { exact: true })).toBeVisible();
    await panel.getByRole("textbox", { name: "Search Ground Stations", exact: true }).clear();
    page.once("dialog", (dialog) => dialog.accept());
    await panel.getByRole("button", { name: "Delete Updated station", exact: true }).click();
    await expect(panel.getByText("No ground stations. Add one to get started.", { exact: true })).toBeVisible();
    expect((await stored_project()).ground_stations).toEqual([]);
    await rail.getByRole("tab", { name: "Network", exact: true }).click();
    await expect(page.getByRole("tabpanel", { name: "Network", exact: true }).getByText("Inter-Satellite Links", { exact: true })).toBeVisible();
    await rail.getByRole("tab", { name: "Tasks", exact: true }).click();
    await expect(page.getByText("Start a simulation to inspect tasks.", { exact: true })).toBeVisible();
    expect(errors).toEqual([]);
  } finally {
    await request.delete(route_path("delete_project", { project_id: project.project_id })).catch(() => undefined);
  }
});
