"""Generate JSON Schema and TypeScript definitions from the Python contracts."""
import json
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from simulator.schemas.project import Project
from simulator.contracts import ControlMessage, StateMessage, StatusMessage, ErrorMessage
from simulator.services.background_jobs import JobSnapshot
from simulator.services.session_records import RecordWindow


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(item) for item in schema["prefixItems"]) + "]"
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object":
        required = set(schema.get("required", []))
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)}'
                  for name, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            fields.append(f"[key: string]: {ts_type(additional)}")
        return "{ " + "; ".join(fields) + " }" if fields else "Record<string, unknown>"
    return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def write_artifact(path: Path, content: str, check: bool) -> None:
    if check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Generated contract is stale: {path.relative_to(ROOT)}")
    else:
        path.write_text(content)


def generate_contracts(check: bool = False) -> None:
    definitions = {}
    for model in [Project, ControlMessage, StateMessage, StatusMessage, ErrorMessage, JobSnapshot, RecordWindow]:
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    bundle = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions}
    destination = ROOT / "frontend/src/features/simulation/contracts"
    destination.mkdir(exist_ok=True)
    write_artifact(destination / "schema.json", json.dumps(bundle, indent=2) + "\n", check)
    lines = ["// Generated by scripts/generate_contracts.py; do not edit."]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export type {name} = {ts_type(schema)};\n")
    write_artifact(destination / "generated.ts", "\n".join(lines), check)
    from simulator.api import router
    routes = {route.name: route.path for route in router.routes}
    write_artifact(destination / "routes.generated.ts", "// Generated from backend/simulator/api.py; do not edit.\nexport const API_ROUTES = " + json.dumps(routes, indent=2) + " as const;\n", check)
    from simulator.defaults import default_project
    write_artifact(destination / "default_project.json", default_project().model_dump_json(indent=2) + "\n", check)
    print(f"Generated {len(definitions)} contract definitions")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate_contracts(parser.parse_args().check)
