import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { route_path } from "../../src/features/simulation/communication/config";
import type { Project } from "../../src/features/simulation/contracts/generated";

test("original monochrome dashboard creates and edits a unified project, including on mobile", async ({ page, request }) => {
  const title = `Dashboard check ${randomUUID().slice(0, 8)}`;
  let project_id: string | null = null;
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  try {
    await page.goto("/dashboard");
    await expect(page.getByRole("heading", { name: "OPHANIM", exact: true })).toBeVisible({ timeout: 30_000 });
    await expect(page.getByTestId("dashboard-earth").locator("canvas")).toBeVisible();
    await expect(page.getByTestId("dashboard-earth")).toHaveCSS("filter", "grayscale(1)");
    await page.waitForLoadState("networkidle");
    await page.screenshot({ path: "test-results/dashboard-restored.png" });
    await page.getByRole("button", { name: "Create Project", exact: true }).click();
    const editor = page.getByRole("dialog", { name: "Create Project", exact: true });
    await expect(editor.getByRole("textbox", { name: "Name", exact: true })).toBeFocused();
    await editor.getByRole("textbox", { name: "Name", exact: true }).fill(title);
    await editor.getByRole("combobox", { name: "Algorithm", exact: true }).selectOption("geometry");
    await editor.getByRole("spinbutton", { name: "Seed", exact: true }).fill("73");
    await editor.getByRole("spinbutton", { name: "Number of Planes", exact: true }).fill("2");
    await editor.getByRole("spinbutton", { name: "Satellites per Plane", exact: true }).fill("3");
    await editor.getByRole("textbox", { name: "Name", exact: true }).focus();
    await page.screenshot({ path: "test-results/project-editor-restored.png" });
    const creation = page.waitForResponse((response) => response.url().endsWith(route_path("save_project")) && response.request().method() === "POST");
    await editor.getByRole("button", { name: "Create Project", exact: true }).click();
    const response = await creation;
    expect(response.ok(), await response.text()).toBeTruthy();
    const project = (await response.json()).data as Project;
    project_id = project.project_id;
    expect(project.algorithm).toBe("geometry");
    expect(project.seed).toBe(73);
    expect(project.satellites).toHaveLength(6);
    await expect(editor).not.toBeVisible();
    await expect(page.getByRole("link", { name: title, exact: false })).toHaveAttribute("href", `/workspace/${project_id}`);
    await page.getByRole("button", { name: `Edit ${title}`, exact: true }).click();
    const edit = page.getByRole("dialog", { name: "Edit Project", exact: true });
    await expect(edit.getByRole("spinbutton", { name: "Seed", exact: true })).toHaveValue("73");
    await edit.getByRole("textbox", { name: "Description", exact: true }).fill("Edited through the original-style form");
    const update = page.waitForResponse((response) => response.url().endsWith(route_path("save_project")) && response.request().method() === "POST");
    await edit.getByRole("button", { name: "Update Project", exact: true }).click();
    expect((await update).ok()).toBeTruthy();
    await expect(edit).not.toBeVisible();
    const stored = (await (await request.get(route_path("get_project", { project_id }))).json()).data as Project;
    expect(stored.description).toBe("Edited through the original-style form");
    expect(stored.seed).toBe(73);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Create Project", exact: true }).click();
    const mobile = page.getByRole("dialog", { name: "Create Project", exact: true });
    await expect(mobile.getByRole("button", { name: "Create Project", exact: true })).toBeVisible();
    expect(await mobile.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBeTruthy();
    await page.screenshot({ path: "test-results/project-editor-mobile.png" });
    await mobile.getByRole("button", { name: "Close", exact: true }).click();
    await page.getByRole("button", { name: "Create Project", exact: true }).click();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("dialog")).not.toBeVisible();
    expect(errors).toEqual([]);
  } finally {
    if (project_id) await request.delete(route_path("delete_project", { project_id }));
  }
});
